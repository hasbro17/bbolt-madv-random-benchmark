#!/usr/bin/env bash
# Build the control and treatment etcd binaries (and shared client tools) from one etcd
# checkout. Treatment differs only by a go.work replace of go.etcd.io/bbolt.
#
# Usage: build.sh --etcd-src DIR --bbolt-treatment DIR --out DIR [--goos OS --goarch ARCH]
# Output: OUT/control/{etcd,etcdctl,benchmark} and OUT/treatment/etcd, plus
#         OUT/versions.env with checksums (SHA_<variant>_<binary>=...).
set -euo pipefail
source "$(dirname "$0")/lib.sh"

etcd_src="" bbolt_src="" out="" goos="" goarch=""
while (($#)); do
  case $1 in
    --etcd-src) etcd_src=$2; shift 2 ;;
    --bbolt-treatment) bbolt_src=$2; shift 2 ;;
    --out) out=$2; shift 2 ;;
    --goos) goos=$2; shift 2 ;;
    --goarch) goarch=$2; shift 2 ;;
    *) die "unknown arg $1" ;;
  esac
done
[[ -d $etcd_src && -d $bbolt_src && -n $out ]] || die "usage: build.sh --etcd-src DIR --bbolt-treatment DIR --out DIR"
etcd_src=$(cd "$etcd_src" && pwd)
bbolt_src=$(cd "$bbolt_src" && pwd)
mkdir -p "$out"
out=$(cd "$out" && pwd)

restore_gowork() { git -C "$etcd_src" checkout -- go.work go.work.sum 2>/dev/null || true; }
trap restore_gowork EXIT

benv=(CGO_ENABLED=0)
[[ -n $goos ]] && benv+=("GOOS=$goos")
[[ -n $goarch ]] && benv+=("GOARCH=$goarch")

build_variant() {
  local variant=$1
  restore_gowork
  if [[ $variant == treatment ]]; then
    (cd "$etcd_src" && go work edit -replace "go.etcd.io/bbolt=$bbolt_src")
  fi
  log "building $variant (${benv[*]})"
  (cd "$etcd_src" && env "${benv[@]}" make build >/dev/null)
  mkdir -p "$out/$variant"
  cp "$etcd_src/bin/etcd" "$out/$variant/etcd"
  if [[ $variant == control ]]; then
    (cd "$etcd_src" && env "${benv[@]}" make tools >/dev/null)
    cp "$etcd_src/bin/etcdctl" "$out/$variant/etcdctl"
    cp "$etcd_src/bin/tools/benchmark" "$out/$variant/benchmark"
  fi
}

build_variant control
build_variant treatment
restore_gowork

# Static check: control links the released bbolt, treatment the replaced one.
ctl_dep=$(go version -m "$out/control/etcd" | awk '$1=="dep" && $2=="go.etcd.io/bbolt"')
trt_dep=$(go version -m "$out/treatment/etcd" | awk '$1=="dep" && $2=="go.etcd.io/bbolt" {getline nxt; print $0; print nxt}')
log "control bbolt:   $ctl_dep"
log "treatment bbolt: $(echo "$trt_dep" | tr '\n' ' ')"
[[ $ctl_dep == *v1.5.0* ]] || die "control is not linked against bbolt v1.5.0"
echo "$trt_dep" | grep -q "^[[:space:]]*=>[[:space:]]*$bbolt_src" || die "treatment does not show the bbolt replace"

{
  echo "# generated by build.sh $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "ETCD_GIT_SHA=$(git -C "$etcd_src" rev-parse HEAD)"
  echo "BBOLT_TREATMENT_GIT_SHA=$(git -C "$bbolt_src" rev-parse HEAD 2>/dev/null || echo unknown)"
  echo "GO_VERSION=$(cd "$etcd_src" && go env GOVERSION)"
  echo "SHA_control_etcd=$(sha256_of "$out/control/etcd")"
  echo "SHA_control_etcdctl=$(sha256_of "$out/control/etcdctl")"
  echo "SHA_control_benchmark=$(sha256_of "$out/control/benchmark")"
  echo "SHA_treatment_etcd=$(sha256_of "$out/treatment/etcd")"
} >"$out/versions.env"
log "wrote $out/versions.env"
cat "$out/versions.env"
